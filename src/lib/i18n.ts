/** Picks `${field}_${lang}` from a bilingual row, falling back to English. */
export function tr<T extends object>(row: T, field: string, lang: Locale): string {
  const r = row as Record<string, unknown>;
  return ((r[`${field}_${lang}`] as string) || (r[`${field}_en`] as string) || "").toString();
}

